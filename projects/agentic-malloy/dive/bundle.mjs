/* bundle.mjs — recombine the modular dive (.dive-preview/src/*) into ONE self-contained
   dive.bundled.tsx for save_dive. Deterministic concat (no esbuild): strip imports, demote
   per-module default exports to named functions, keep the single StoryDive default export,
   hoist one external-import block. Edit the modules, not the bundle. */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.join(HERE, ".dive-preview", "src");
const ORDER = ["lib.tsx", "StoryTab.tsx", "MetricsTab.tsx", "BuildTab.tsx", "LayerTab.tsx", "TracesTab.tsx", "dive.tsx"];

const HEADER = `// AUTO-GENERATED by dive/bundle.mjs — do not edit. Source: dive/.dive-preview/src/*
import { useState } from "react";
import { useSQLQuery, useDiveState } from "@motherduck/react-sql-query";
import { BarChart, Bar, XAxis, YAxis, ReferenceLine, LabelList, ResponsiveContainer } from "recharts";
import { Loader2 } from "lucide-react";
`;

const strip = (src) =>
  src.split("\n")
    .filter((l) => !/^\s*import\s/.test(l))                              // drop all imports
    .map((l) => {
      if (/^\s*export\s+default\s+function\s+StoryDive\b/.test(l)) return l; // the one real default
      return l
        .replace(/^(\s*)export\s+default\s+function\s+/, "$1function ")  // tab defaults -> named
        .replace(/^(\s*)export\s+/, "$1");                              // strip remaining export kw
    })
    .join("\n");

const body = ORDER.map((f) => `\n// ───────── ${f} ─────────\n` + strip(readFileSync(path.join(SRC, f), "utf8"))).join("\n");
const out = HEADER + body + "\n";
writeFileSync(path.join(HERE, "dive.bundled.tsx"), out);

const defaults = (out.match(/export\s+default/g) || []).length;
// Guard: flattening modules into one scope means top-level names must be unique.
const decls = [...out.matchAll(/^(?:const|function) ([A-Za-z_$][\w$]*)/gm)].map((m) => m[1]);
const dups = [...new Set(decls.filter((n, i) => decls.indexOf(n) !== i))];
console.log(`wrote dive.bundled.tsx (${out.length} bytes, ${defaults} default export${defaults === 1 ? "" : "s"})`);
if (defaults !== 1) { console.error("ERROR: expected exactly 1 default export"); process.exit(1); }
if (dups.length) { console.error("ERROR: duplicate top-level declarations (will collide at runtime):", dups); process.exit(1); }
console.log(`no duplicate top-level declarations (${decls.length} checked)`);
