#!/usr/bin/env node
/**
 * Packs the Univer UMD bundles the supply grid needs into src/univer-vendor.generated.ts.
 *
 * Reads dive/vendor-cache (populated by scripts/fetch-vendor.sh). Only the
 * plugins the supply grid uses are included (sheets, formulas, number formats), and all of
 * it is gzip+base64'd into one blob; univer-runtime.ts inflates it with the
 * browser's DecompressionStream and evaluates each file in global scope.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { gzipSync } from "node:zlib";
import { fileURLToPath } from "node:url";
import { dirname, relative, resolve } from "node:path";

const HERE = dirname(fileURLToPath(import.meta.url));
const VENDOR = process.env.UNIVER_VENDOR_DIR
  ?? resolve(HERE, "../vendor-cache");
const OUT = resolve(HERE, "../src/univer-vendor.generated.ts");

// Load order mirrors Univer's examples/umd/sheets.html: each file may only
// reference globals registered by earlier ones.
const SCRIPTS = [
  "rxjs.js", "redi.js", "redi-react.js", "themes.js", "protocol.js",
  "core.js", "telemetry.js", "rpc.js", "design.js", "engine-render.js", "engine-formula.js",
  "drawing.js", "ui.js", "docs.js", "docs-ui.js", "sheets.js", "sheets-ui.js",
  "sheets-formula.js", "sheets-formula-ui.js", "sheets-numfmt.js", "sheets-numfmt-ui.js",
  "core.facade.js", "engine-formula.facade.js", "ui.facade.js", "docs-ui.facade.js",
  "sheets.facade.js", "sheets-ui.facade.js", "sheets-formula.facade.js", "sheets-numfmt.facade.js",
  "design.enUS.js", "ui.enUS.js", "docs-ui.enUS.js", "sheets.enUS.js", "sheets-ui.enUS.js",
  "sheets-formula-ui.enUS.js", "sheets-numfmt-ui.enUS.js",
];
const CSS = ["design.css", "ui.css", "docs-ui.css", "sheets-ui.css", "sheets-formula-ui.css", "sheets-numfmt-ui.css"];

const read = (f) => {
  const p = resolve(VENDOR, f);
  if (!existsSync(p)) throw new Error(`Missing ${p} — run scripts/fetch-vendor.sh`);
  return readFileSync(p, "utf8");
};
const blob = (files) => gzipSync(Buffer.from(JSON.stringify(files.map((name) => ({ name, code: read(name) })))), { level: 9 }).toString("base64");

const scripts = blob(SCRIPTS);
const css = blob(CSS);
writeFileSync(OUT, `// GENERATED by scripts/build-vendor.mjs — do not edit.\n// Univer UMD bundles from ${relative(resolve(HERE, ".."), VENDOR)} (${SCRIPTS.length} scripts, ${CSS.length} stylesheets), gzip+base64.\nexport const UNIVER_SCRIPTS_B64 = ${JSON.stringify(scripts)};\nexport const UNIVER_CSS_B64 = ${JSON.stringify(css)};\n`);
console.log(`[build-vendor] scripts ${(scripts.length / 1e6).toFixed(2)} MB, css ${(css.length / 1e3).toFixed(0)} KB (base64) -> ${OUT}`);
