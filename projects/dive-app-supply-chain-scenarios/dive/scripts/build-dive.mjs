#!/usr/bin/env node
/**
 * Bundles src/dive.tsx into a single-file Dive for one deploy target.
 *
 *   npm run vendor                          # once: fetch + pack the Univer UMD bundles
 *   node scripts/build-dive.mjs <target>    # -> build/supply-chain-scenarios.<target>.jsx
 *
 * The target's share URL and write Flight id come from deploy-targets.json
 * (written by ../flight/setup.py). Everything the Dive runtime provides stays an
 * import (react, react-dom, recharts, lucide-react, @motherduck/react-sql-query);
 * everything else, including Univer, is inlined. JSX is compiled to
 * React.createElement because the runtime does not expose react/jsx-runtime.
 */
import { build } from "esbuild";
import { existsSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const TARGET_NAME = process.argv[2] || process.env.TARGET;
if (!TARGET_NAME) throw new Error("usage: node scripts/build-dive.mjs <target>   (a key of deploy-targets.json)");
const TARGETS_FILE = resolve(ROOT, "deploy-targets.json");
if (!existsSync(TARGETS_FILE)) throw new Error("deploy-targets.json is missing: run ../flight/setup.py <target> first");
const TARGET = JSON.parse(readFileSync(TARGETS_FILE, "utf8"))[TARGET_NAME];
if (!TARGET?.share_url || !TARGET?.write_flight_id) throw new Error(`deploy-targets.json has no share_url / write_flight_id for ${TARGET_NAME}`);
if (!existsSync(resolve(ROOT, "src", "univer-vendor.generated.ts"))) throw new Error("src/univer-vendor.generated.ts is missing: run `npm run vendor` first");
const ENTRY = resolve(ROOT, "src", "dive.tsx");
const OUT = resolve(ROOT, "build", `supply-chain-scenarios.${TARGET_NAME}.jsx`);
const RUNTIME = ["react", "react-dom", "react-dom/client", "recharts", "lucide-react", "@motherduck/react-sql-query"];

await build({
  entryPoints: [ENTRY],
  outfile: OUT,
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2020",
  jsx: "transform",
  jsxFactory: "React.createElement",
  jsxFragment: "React.Fragment",
  external: RUNTIME,
  minifySyntax: true,
  minifyWhitespace: true,
  legalComments: "none",
  define: { __WRITE_FLIGHT_ID__: JSON.stringify(TARGET.write_flight_id) },
  banner: { js: "// Supply Chain Scenario Modeling Dive — generated by dive/scripts/build-dive.mjs from dive/src. Do not edit." },
});

let code = readFileSync(OUT, "utf8");
// MotherDuck reads REQUIRED_DATABASES statically from an
// `export const REQUIRED_DATABASES = [...]` declaration, but esbuild emits a
// `var` plus `export { REQUIRED_DATABASES }`. Re-emit the source's literal
// declaration (with this target's share) and drop the bundler's copy.
const src = readFileSync(ENTRY, "utf8");
const srcDecl = src.match(/export const REQUIRED_DATABASES = \[[\s\S]*?\n\];/)?.[0];
if (!srcDecl) throw new Error("src/dive.tsx must declare `export const REQUIRED_DATABASES = [...]`");
const decl = srcDecl.replace(/md:_share\/[^"]+/, TARGET.share_url);
if (!decl.includes(TARGET.share_url)) throw new Error("REQUIRED_DATABASES must name the planner share");
code = code.replace(/\bREQUIRED_DATABASES\b/g, "REQUIRED_DATABASES_BUNDLED")
  .replace(/export\s*\{([^}]*)\}\s*;?\s*$/, (_m, list) =>
    `export{${list.split(",").filter((x) => !/REQUIRED_DATABASES_BUNDLED/.test(x)).join(",")}};\n${decl}\n`);
writeFileSync(OUT, code);
const imports = [...code.matchAll(/(?:^|[;\n])import\s*(?:[^;"]*?from\s*)?"([^"]+)"/g)].map((m) => m[1]);
const stray = imports.filter((i) => !RUNTIME.includes(i));
if (stray.length) throw new Error(`Non-runtime imports left in the bundle: ${[...new Set(stray)].join(", ")}`);
if (/\bimport\(/.test(code)) throw new Error("Dynamic import() is not allowed in a Dive");
if (!/\nexport const REQUIRED_DATABASES = \[/.test(code) || !/export\s*\{[^}]*as default/.test(code)) throw new Error("Bundle must export default + REQUIRED_DATABASES");
console.log(`[build-dive] ${(statSync(OUT).size / 1e6).toFixed(2)} MB -> ${OUT} (${TARGET_NAME})`);
