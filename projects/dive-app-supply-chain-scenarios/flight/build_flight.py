#!/usr/bin/env python3
"""Builds the single-file Flight source: build/supply_planner_write.py.

A Flight is one Python file, so this inlines supply_engine.py and planner.py
as modules (the names write_flight.py imports) above write_flight.py's code.

  python3 flight/build_flight.py
"""
from __future__ import annotations

import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "build", "supply_planner_write.py")
IMPORT = "from planner import Api, ApiError, Store, _clean_text, ensure_rpc_results, now_utc, SCHEMA\n"


def module(name: str, path: str) -> list[str]:
    return [
        f"# ── {os.path.basename(path)}, as the `{name}` module ──",
        f"_{name.upper()}_SRC = {open(path).read()!r}",
        f'{name} = types.ModuleType("{name}")',
        f"{name}.__file__ = {os.path.basename(path)!r}",
        f'sys.modules["{name}"] = {name}',
        f'exec(compile(_{name.upper()}_SRC, "{os.path.basename(path)}", "exec"), {name}.__dict__)',
        "",
    ]


def main():
    entry = open(os.path.join(HERE, "write_flight.py")).read()
    if IMPORT not in entry:
        raise SystemExit("write_flight.py must import planner exactly as build_flight.py expects")
    out = "\n".join([
        "# supply-planner-write Flight — generated by flight/build_flight.py from",
        "# flight/supply_engine.py, flight/planner.py and flight/write_flight.py. Do not edit.",
        "import sys",
        "import types",
        "",
        *module("supply_engine", os.path.join(HERE, "supply_engine.py")),
        *module("planner", os.path.join(HERE, "planner.py")),
        "# ── write_flight.py ──",
        entry,
    ])
    compile(out, OUT, "exec")
    if len(out.encode()) > 200_000:
        raise SystemExit(f"Flight source is {len(out.encode())} bytes; the limit is 200 KB")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write(out)
    print(f"[build-flight] {len(out.encode()) / 1000:.1f} KB -> {OUT}")


if __name__ == "__main__":
    main()
